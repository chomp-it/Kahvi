def camelize(string, first_letter_upper: false)
  words = string
          .gsub(/([a-z\d])([A-Z])/, '\1 \2')
          .scan(/[a-zA-Z0-9]+/)

  return '' if words.empty?

  # Capitalize each word
  capitalized_words = words.map(&:capitalize)

  # Lowercase the very first word if lower camelCase is required
  capitalized_words[0] = capitalized_words[0].downcase unless first_letter_upper

  capitalized_words.join
end

def translate_event old_event
  case old_event
  when 'clicked'                   then 'click'
  when 'submitted'                 then 'submit'
  when 'highlighted', 'mousedover' then 'mouseover'
  when 'unhighlighted', 'mouseoff' then 'mouseout'
  when 'typed', 'typing'           then 'input'
  when 'changed'                   then 'change'
  else old_event
  end
end

$lastFunctionName = nil
$inFunction       = false

def generate token
  snippets = []

  snippet = case token[:type]
            when :event_listener          then generate_event_listener token
            when :input_enforcement       then generate_enforcement token
            when :element_assignment      then generate_element_assignment token
            when :hide                    then generate_hide_element token
            when :display                 then generate_display_element token
            when :type_mutation           then generate_type_mutation token
            when :aint_condition          then generate_aint_condition token
            when :perform                 then generate_perform token
            when :end                     then generate_end token
            when :kahvi_confirm           then generate_kahvi_confirm token
            when :alternate_function      then generate_alternate_function token
            when :get_element             then generate_get_element token
            when :right_now               then generate_right_now token
            when :get_request             then generate_get_request token
            when :oris_conditional        then generate_oris_conditional token
            when :flip                    then generate_boolean_flip token
            when :variable_event_listener then generate_variable_event_listener token
            when :wait                    then generate_wait token
            when :do_after_cooldown       then generate_do_after_cooldown token
            when :toggle_display          then generate_toggle_display token
            when :coffeescript            then handle_coffeescript token[:value]
            end

  snippets << snippet
end

def generate_coffeescript file_to_read_from, file_to_write_to
  unless File.exist?(file_to_read_from)
    puts <<~END
      Failed to locate #{file_to_read_from} in this directory.
      Perhaps you forgot the file extension, or maybe you are in the wrong directory.
    END
    exit
  end

  lines    = File.readlines(file_to_read_from)
  tokens   = lines.map { |line| lex line.chomp }
  snippets = tokens.map { |token| generate token }

  if file_to_write_to.nil?
    puts 'You must provide an output file.'
    exit
  end

  File.open(file_to_write_to, 'w') do |file|
    file.puts '# Generated by French Press CoffeeScript'
    snippets.each do |snippet|
      file.puts snippet
    end
  end
end

# compile
def output_coffeescript file_in, file_out
  generate_coffeescript file_in, file_out
  puts 'Done brewing. Enjoy your CoffeeScript.'
end

# full_send
def output_javascript file_in, file_out
  generate_coffeescript file_in, file_out

  `coffee --compile #{file_out}`

  unless $?.success?
    puts 'Something went wrong with the coffeescript compilation process.'
    exit
  end
end

# what-is-kahvi
